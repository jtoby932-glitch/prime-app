G = {}


def g(slug, p, o, s, m, e, h, sf=(), u=False, t=None, pm=None, sm=None):
    """Registers a guide. p = pattern, o = overview, s = setup, m = (what, why, fix) mistakes,
    e = easier, h = harder, sf = extra safety, u = unilateral, t = tracking override,
    pm / sm = primary / secondary muscle overrides for entries written before v2."""
    assert p in PATTERNS, f"{slug}: unknown pattern {p}"
    G[slug] = dict(p=p, o=o, s=list(s), m=[tuple(x) for x in m], e=list(e), h=list(h), sf=list(sf), u=u, t=t, pm=pm, sm=sm)


